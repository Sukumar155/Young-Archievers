/**
 * gen-vercel-routes.mjs — generate one Vercel function file per API route.
 *
 * Why explicit files instead of a catch-all
 * -----------------------------------------
 * A single `api/[...path].ts` was tried first and deployed as a single-segment
 * matcher: /api/health and /api/sos worked, but /api/auth/otp/status and every
 * other nested route returned a 404 that never reached the function. Verified
 * live — a 1-segment path returned the function's JSON 404, a 2-segment path
 * returned Vercel's own empty text/plain 404. Renaming the parameter and
 * switching between [...x] and [[...x]] did not change it.
 *
 * Rather than keep fighting catch-all semantics, give every route its own file.
 * `api/auth/otp/status.ts` maps to /api/auth/otp/status by plain filesystem
 * routing, which needs no wildcard interpretation at all.
 *
 * Each generated file is a three-line re-export of the shared handler, so this
 * is a layout change, not a second copy of the logic.
 *
 * Run:  node scripts/gen-vercel-routes.mjs [--check]
 *        --check fails if the files on disk differ from what would be generated.
 */
import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const API = join(ROOT, 'api');
const CHECK = process.argv.includes('--check');

/**
 * The route table. Kept here as the single source of truth and cross-checked
 * against the dispatcher in sos-server.mjs by verify-vercel-routing.mjs, so a
 * route added to one and forgotten in the other is caught rather than shipped.
 */
const ROUTES = [
  { file: 'index.ts',             path: '/',                     doc: 'Browser view of the bridge, served at / and /api.' },
  { file: 'health.ts',            path: '/api/health',            doc: 'Liveness plus database and runtime state.' },
  { file: 'sos.ts',               path: '/api/sos',               doc: 'List and submit SOS beacons.' },
  { file: 'sos/[id].ts',          path: '/api/sos/:id',           doc: 'Triage a single SOS report.' },
  { file: 'chat.ts',              path: '/api/chat',              doc: 'Chatbot completion, proxied to the configured AI provider.' },
  { file: 'events.ts',            path: '/api/events',            doc: 'Server-Sent Events feed (501 on serverless).' },
  { file: 'yolo/detect.ts',       path: '/api/yolo/detect',       doc: 'YOLO inference (501 on serverless — needs Python and model weights).' },
  { file: 'auth/otp/request.ts',  path: '/api/auth/otp/request',  doc: 'Issue a login OTP.' },
  { file: 'auth/otp/verify.ts',   path: '/api/auth/otp/verify',   doc: 'Exchange an OTP for a session token.' },
  { file: 'auth/otp/status.ts',   path: '/api/auth/otp/status',   doc: 'Report whether a real SMS gateway is configured.' },
  { file: 'auth/session.ts',      path: '/api/auth/session',      doc: 'Describe the current session.' },
  { file: 'alerts.ts',            path: '/api/alerts',            doc: 'List and broadcast CAP alerts.' },
  { file: 'alerts/[id].ts',       path: '/api/alerts/:id',        doc: 'Update one alert.' },
  { file: 'incidents.ts',         path: '/api/incidents',         doc: 'List and file incidents.' },
  { file: 'incidents/[id].ts',    path: '/api/incidents/:id',     doc: 'Update one incident.' },
  { file: 'plain.ts',             path: '/api/plain',             doc: 'Plain-text endpoint listing, kept for scripts that scrape it.' },
];

function source(doc, file) {
  // Climb back out of however many directories this file sits in, so
  // auth/otp/request.ts reaches api/_lib with ../../ rather than ../. Getting
  // this wrong typechecks as an unresolved import the moment api/ is built.
  const depth = file.split('/').length - 1;
  const up = depth === 0 ? './_lib/' : '../'.repeat(depth) + '_lib/';
  return `/**
 * ${doc}
 *
 * Generated by scripts/gen-vercel-routes.mjs — edit the generator, not this
 * file. It re-exports the shared handler, which delegates to the same
 * handleRequest() that \`npm start\` uses, so the deployed routes and the local
 * server cannot drift apart.
 */
import { handler } from '${up}handler.js';
import type { VercelRequest, VercelResponse } from '${up}types.js';

export const config = { maxDuration: 60 };

export default function route(req: VercelRequest, res: VercelResponse): void {
  handler(req, res);
}
`;
}

let written = 0;
const expected = new Set();

for (const r of ROUTES) {
  const abs = join(API, r.file);
  expected.add(r.file);
  const body = source(r.doc, r.file);
  mkdirSync(dirname(abs), { recursive: true });

  if (CHECK) {
    const current = existsSync(abs) ? readFileSync(abs, 'utf8') : '';
    if (current !== body) {
      console.error(`  STALE  api/${r.file}`);
      process.exitCode = 1;
    }
  } else {
    const current = existsSync(abs) ? readFileSync(abs, 'utf8') : '';
    if (current !== body) {
      writeFileSync(abs, body, 'utf8');
      console.log(`  wrote  api/${r.file}`);
      written++;
    }
  }
}

// Remove any route file that is no longer in the table, so a deleted route does
// not keep answering on Vercel.
if (!CHECK && existsSync(API)) {
  const { readdirSync, statSync } = await import('node:fs');
  const walk = dir => {
    for (const name of readdirSync(dir)) {
      const p = join(dir, name);
      if (name.startsWith('_')) continue;
      if (statSync(p).isDirectory()) { walk(p); continue; }
      if (!name.endsWith('.ts')) continue;
      const rel = relative(API, p).replace(/\\/g, '/');
      if (!expected.has(rel)) {
        rmSync(p);
        console.log(`  removed api/${rel}`);
      }
    }
  };
  walk(API);
}

console.log(
  CHECK
    ? (process.exitCode ? 'FAIL - generated routes are stale' : `PASS - ${ROUTES.length} route files up to date`)
    : `done - ${ROUTES.length} routes (${written} changed)`
);
